"""Write Formula/jira-cli-toolkit.rb from a published CLI Toolkit for Jira release.

Usage: python scripts/update_formula.py [TAG]   (default: latest stable release)

Reads the release's manifest.json and uses its binary SHA-256 values. Prereleases are
refused. The workflow verifies each binary's GitHub attestation before committing.
"""
import json
import os
import sys
import urllib.request
from pathlib import Path

REPO = "User17745/jira-cli-toolkit"
FORMULA = Path(__file__).resolve().parents[1] / "Formula" / "jira-cli-toolkit.rb"
TARGETS = {("macos", "arm64"): "macos-arm64", ("macos", "x86_64"): "macos-x86_64", ("linux", "x86_64"): "linux-x86_64"}


def get(url):
    request = urllib.request.Request(url, headers={"Accept": "application/vnd.github+json", "User-Agent": "homebrew-tap"})
    if os.getenv("GH_TOKEN"):
        request.add_header("Authorization", "Bearer " + os.environ["GH_TOKEN"])
    with urllib.request.urlopen(request, timeout=60) as response:
        return response.read()


def main():
    tag = sys.argv[1] if len(sys.argv) > 1 else None
    release = json.loads(get(f"https://api.github.com/repos/{REPO}/releases/" + (f"tags/{tag}" if tag else "latest")))
    if release.get("prerelease") or release.get("draft"):
        raise SystemExit(f"{release['tag_name']} is not a stable release.")
    manifest = json.loads(get(f"https://github.com/{REPO}/releases/download/{release['tag_name']}/manifest.json"))
    if manifest.get("repository") != REPO or manifest.get("channel") != "stable" or manifest.get("tag") != release["tag_name"]:
        raise SystemExit("Manifest does not describe this stable release.")
    sha = {}
    for item in manifest["artifacts"]:
        key = TARGETS.get((item.get("os"), item.get("arch")))
        if item.get("kind") == "binary" and key:
            if item["name"] != f"jira-cli-toolkit-{key}" or len(item["sha256"]) != 64:
                raise SystemExit(f"Unexpected binary entry: {item}")
            sha[key] = item["sha256"]
    if set(sha) != set(TARGETS.values()):
        raise SystemExit("Release is missing a macOS or Linux binary.")
    version = manifest["version"]
    base = f"https://github.com/{REPO}/releases/download/v{version}/jira-cli-toolkit"
    FORMULA.write_text(f'''# Generated by scripts/update_formula.py from the release manifest; edit the script, not this file.
class JiraCliToolkit < Formula
  desc "Independent CLI for Jira Cloud issues, sprints and REST APIs"
  homepage "https://jira.abhishekaggarwal.com/"
  license "AGPL-3.0-only"

  livecheck do
    url :stable
    strategy :github_latest
  end

  on_macos do
    depends_on macos: :sequoia

    on_arm do
      url "{base}-macos-arm64"
      sha256 "{sha['macos-arm64']}"
    end
    on_intel do
      url "{base}-macos-x86_64"
      sha256 "{sha['macos-x86_64']}"
    end
  end

  on_linux do
    # Only an x86_64 Linux binary is published.
    depends_on arch: :x86_64

    url "{base}-linux-x86_64"
    sha256 "{sha['linux-x86_64']}"
  end

  def install
    # Each release asset is a single self-contained executable, installed as `jira`.
    bin.install Dir["jira-cli-toolkit-*"].fetch(0) => "jira"
  end

  test do
    assert_equal "jira #{{version}}", shell_output("#{{bin}}/jira --version").strip
    assert_match "usage: jira issue list", shell_output("#{{bin}}/jira help issue list")
    # Updates belong to Homebrew; the CLI must not replace its own Cellar files.
    if version >= Version.new("2.5.2")
      assert_match '"method": "homebrew"', shell_output("#{{bin}}/jira update --info --json")
    end
  end
end
''')
    print(f"Formula updated to {version}")


if __name__ == "__main__":
    main()
